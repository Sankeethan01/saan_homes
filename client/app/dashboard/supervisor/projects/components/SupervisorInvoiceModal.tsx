import { useState } from "react";
import { RiCloseLine } from "react-icons/ri";
import { fetchWithAuth } from "@/app/utils/auth";
import { jsPDF } from "jspdf";

interface Step {
  id: string;
  title: string;
  thumbnail?: string;
}

interface Invoice {
  id: string;
  amount: number;
  date: string;
  status: string;
}

interface SupervisorInvoiceModalProps {
  open: boolean;
  step: Step;
  invoice?: Invoice;
  onClose: () => void;
  onSaved?: () => void;
}

const getThumbnailUrl = (thumbnail: string) => {
  if (!thumbnail) return "";
  if (thumbnail.startsWith("http://") || thumbnail.startsWith("https://")) {
    return thumbnail;
  }
  return `${process.env.NEXT_PUBLIC_API_BASE_URL}/media/${thumbnail}`;
};

const fetchImageAsBase64 = async (url: string) => {
  const response = await fetch(url);
  const blob = await response.blob();
  return new Promise<string>((resolve, reject) => {
    const reader = new FileReader();
    reader.onloadend = () => resolve(reader.result as string);
    reader.onerror = reject;
    reader.readAsDataURL(blob);
  });
};

// Updated fetch helper for logo image inside the public folder
const fetchImageFromPublicAsBase64 = async (filename: string) => {
  const response = await fetch(`/assets/images/${filename}`); // Updated path
  if (!response.ok) {
    throw new Error(`Failed to load image: ${filename}`);
  }
  const blob = await response.blob();
  return new Promise<string>((resolve, reject) => {
    const reader = new FileReader();
    reader.onloadend = () => {
      const result = reader.result as string;
      if (!result.startsWith("data:image/")) {
        reject("Not a valid image");
      } else {
        resolve(result);
      }
    };
    reader.onerror = reject;
    reader.readAsDataURL(blob);
  });
};

export default function SupervisorInvoiceModal({
  open,
  step,
  onClose,
  onSaved,
}: SupervisorInvoiceModalProps) {
  const [form] = useState({
    files: [] as File[],
  });
  const [saving, setSaving] = useState(false);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (form.files.length === 0) {
      alert("Please upload at least one PDF bill.");
      return;
    }
    setSaving(true);
    try {
      for (const file of form.files) {
        const fd = new FormData();
        fd.append("step", step.id);
        fd.append("pdf", file);
        await fetchWithAuth(`${process.env.NEXT_PUBLIC_API_BASE_URL}/projects/bills/`, {
          method: "POST",
          body: fd,
        });
      }
      if (onSaved) onSaved();
      onClose();
    } catch {
      alert("Failed to submit bills.");
    } finally {
      setSaving(false);
    }
  };

  const handleDownload = async () => {
    try {
      let logo = await fetchImageFromPublicAsBase64("logo-01.png"); // Updated logo name and path

      if (step?.thumbnail) {
        try {
          logo = await fetchImageAsBase64(getThumbnailUrl(step.thumbnail));
        } catch {
          console.warn("Using fallback logo from public folder");
        }
      }

      const imageTypeMatch = logo.match(/^data:image\/(png|jpeg|jpg);base64,/i);
      const imageType = imageTypeMatch?.[1]?.toUpperCase() || "PNG";

      const doc = new jsPDF();
      doc.addImage(logo, imageType, 10, 8, 25, 15);
      doc.setFontSize(18);
      doc.setTextColor(40, 40, 40);
      doc.text("Saan Homes", 40, 18);
      doc.setFontSize(14);
      doc.setTextColor(80, 80, 80);
      doc.text("Step Invoice", 10, 32);
      doc.setDrawColor(180, 180, 180);
      doc.line(10, 35, 200, 35);
      doc.setFontSize(12);
      doc.setTextColor(50, 50, 50);
      let y = 45;
      doc.text(`Step:`, 10, y);
      doc.text(`${step?.title || ""}`, 40, y);
      y += 10;
      doc.text(`Amount:`, 10, y);
      y += 30;
      doc.setFontSize(10);
      doc.setTextColor(120, 120, 120);
      doc.text("Generated by Saan Homes Supervisor Portal", 10, y);
      doc.save(`Invoice_${step?.title || "step"}.pdf`);
    } catch (error) {
      console.error("Error generating PDF:", error);
      alert("Failed to generate PDF.");
    }
  };

  if (!open) return null;

  return (
    <div className="fixed inset-0 bg-black/50 flex items-center justify-center z-50">
      <div className="bg-white rounded-2xl p-6 w-full max-w-md mx-4 max-h-[90vh] overflow-y-auto">
        <div className="flex items-center justify-between mb-4">
          <h3 className="text-lg font-semibold">Step Invoice</h3>
          <button 
            onClick={onClose} 
            className="text-gray-400 hover:text-gray-600"
            title="Close modal"
            aria-label="Close modal"
          >
            <RiCloseLine className="w-5 h-5" />
          </button>
        </div>
        <form onSubmit={handleSubmit} className="space-y-4">
          <div className="flex gap-4 mt-6">
            <button
              type="button"
              onClick={onClose}
              className="flex-1 px-4 py-2 border border-gray-300 rounded-lg text-gray-700 hover:bg-gray-50"
              disabled={saving}
            >
              Cancel
            </button>
            <button
              type="submit"
              className="flex-1 px-4 py-2 bg-green-700 text-white rounded-lg hover:bg-green-800 disabled:opacity-50 disabled:cursor-not-allowed"
              disabled={saving}
            >
              {saving ? "Submitting..." : "Submit to Admin"}
            </button>
            <button
              type="button"
              onClick={handleDownload}
              className="flex-1 px-4 py-2 border border-blue-500 text-blue-700 rounded-lg hover:bg-blue-50"
              disabled={saving}
            >
              Download Invoice
            </button>
            <button
              type="button"
              onClick={() => {
                // Focus the file input to allow editing bills (no-op since no field)
              }}
              className="flex-1 px-4 py-2 border border-yellow-500 text-yellow-700 rounded-lg hover:bg-yellow-50"
              disabled={saving}
            >
              Edit Invoice
            </button>
          </div>
        </form>
      </div>
    </div>
  );
}
